#!/usr/bin/env python3
"""Copyright guard: fail if anything from the game is about to be committed.

  python tools/check_no_game_data.py               # every tracked file
  python tools/check_no_game_data.py --staged      # only staged files (the pre-commit hook)
  python tools/check_no_game_data.py --install-hook

Refuses: disc images and cue sheets, memory cards and saves, BIOS images, the game's programs
(PS-X EXE header), raw CD sectors, code generated from the game (the recompiler's header), capture
files that carry the game's code (bytes_b64), and any other binary over 1 MB unless listed in
tools/game_data_allowlist.txt (our own or freely licensed files only).
"""
from __future__ import annotations

import argparse
import hashlib
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

FORBIDDEN_EXTS = {
    ".bin", ".cue", ".iso", ".img", ".chd", ".ecm", ".pbp", ".ccd", ".sub", ".mds", ".mdf",
    ".mcd", ".mcr", ".gme", ".vmp", ".psv", ".srm", ".sav", ".sstate",
    ".apk", ".tga",
}
# Allowed despite the extension (our own files): none yet.
ALLOWED_PATHS: set[str] = set()

MAGICS = [
    (0, b"PS-X EXE", "a PlayStation program"),
    (0, b"\x00\xff\xff\xff\xff\xff\xff\xff\xff\xff\xff\x00", "a raw CD sector (disc image)"),
    (0, b"MC\x00\x00", "a memory card image"),
    (0, b"\x1f\x8b\x08", "a gzip stream (game modules on the disc are gzip)"),
]
TEXT_MARKERS = [  # (marker, the file types it applies to, what it means)
    (b"Generated by PSXRecomp", {".c", ".h", ".cpp", ".inc"}, "code generated from the game"),
    (b"\"bytes_b64\"", {".json"}, "captured game code (bytes_b64)"),
]
# Verification facts, not data: a file with one of these hashes IS a supported disc (listed in game/port.ps1).
_PORT = REPO / "game" / "port.ps1"
KNOWN_DISC_SHA1 = set(re.findall(r"\b[0-9a-f]{40}\b", _PORT.read_text(encoding="utf-8"))) if _PORT.exists() else set()
MAX_BINARY_SIZE = 1 * 1024 * 1024
ALLOWLIST_FILE = REPO / "tools" / "game_data_allowlist.txt"


def git(*args: str) -> list[str]:
    out = subprocess.run(["git", *args], cwd=REPO, check=True, capture_output=True, text=True).stdout
    return [line for line in out.splitlines() if line]


def allowlist() -> set[str]:
    if not ALLOWLIST_FILE.exists():
        return set()
    return {l.split("#")[0].strip() for l in ALLOWLIST_FILE.read_text().splitlines() if l.split("#")[0].strip()}


def is_binary(data: bytes) -> bool:
    if b"\0" in data[:8192]:
        return True
    try:
        data[:8192].decode("utf-8")
        return False
    except UnicodeDecodeError:
        return True


def check(rel: str, data: bytes, allowed: set[str]) -> list[str]:
    why = []
    ext = Path(rel).suffix.lower()
    if ext in FORBIDDEN_EXTS and rel not in ALLOWED_PATHS:
        why.append(f"{ext} files are never committed (discs, saves, BIOS, builds)")
    name = Path(rel).name.upper()
    if name.startswith(("SCUS_", "SCES_", "SLUS_", "SLES_", "SCPS_", "SLPS_")) or name.startswith("SCPH"):
        why.append("named like a game program or a BIOS")
    for off, magic, what in MAGICS:
        if data[off:off + len(magic)] == magic:
            why.append(what)
    for marker, exts, what in TEXT_MARKERS:
        if ext in exts and marker in data:
            why.append(what)
    if hashlib.sha1(data).hexdigest() in KNOWN_DISC_SHA1:
        why.append("this is a supported disc image")
    if is_binary(data) and len(data) > MAX_BINARY_SIZE and rel not in allowed:
        why.append(f"binary over {MAX_BINARY_SIZE // 1024} KB (add it to {ALLOWLIST_FILE.name} if it is ours)")
    return why


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--staged", action="store_true")
    ap.add_argument("--install-hook", action="store_true")
    ap.add_argument("paths", nargs="*")
    a = ap.parse_args()
    if a.install_hook:
        hook = Path(git("rev-parse", "--git-path", "hooks")[0])
        if not hook.is_absolute():
            hook = REPO / hook
        hook.mkdir(parents=True, exist_ok=True)
        (hook / "pre-commit").write_text("#!/bin/sh\nexec python tools/check_no_game_data.py --staged\n")
        print(f"installed {hook / 'pre-commit'}")
        return 0
    if a.paths:
        files = a.paths
    elif a.staged:
        files = git("diff", "--cached", "--name-only", "--diff-filter=ACMR")
    else:
        files = git("ls-files")
    allowed = allowlist()
    bad = 0
    for rel in files:
        p = REPO / rel
        if not p.is_file():
            continue  # submodules, deleted files
        reasons = check(rel.replace("\\", "/"), p.read_bytes(), allowed)
        if reasons:
            bad += 1
            print(f"REFUSED {rel}: {'; '.join(reasons)}")
    print(f"checked {len(files)} file(s): {'OK, nothing from the game' if not bad else f'{bad} refused'}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
